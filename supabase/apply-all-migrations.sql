# Create IT asset management core data

1. New Tables
- `it_assets` stores the asset register, lifecycle state, ownership, warranty, and financial details.
- `it_invoices` stores invoice queue records, matching state, and totals.
- `it_tickets` stores service desk work with priority, SLA, assignee, and status.
- `it_purchase_requests` stores procurement requests, approval status, and spend.

2. Security
- Row-level security is enabled on every table.
- This initial workspace is intentionally single-tenant and has no sign-in screen, so anon and authenticated roles receive CRUD access for the shared operational dataset.

3. Important Notes
- UUIDs are generated by Postgres.
- Monetary values use numeric columns and asset tags are unique.
- This migration creates structure only; operational data is entered through the application.
