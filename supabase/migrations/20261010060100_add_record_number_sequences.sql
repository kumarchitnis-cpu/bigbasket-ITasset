/*
# Add server-side record numbering for tickets and purchase requests

1. Purpose
- Ticket numbers and purchase request numbers are now generated by the database
  from dedicated sequences, so the application never invents or reuses identifiers.
- Inserts that omit ticket_number / request_number receive the next number
  automatically (e.g. TKT-000001, PR-000001).

2. Important Notes
- Existing rows keep their current numbers; sequences start after the seed range.
- The UNIQUE constraints remain in force, so collisions still fail loudly.
*/

CREATE SEQUENCE IF NOT EXISTS it_tickets_ticket_number_seq START 2049;
ALTER TABLE it_tickets ALTER COLUMN ticket_number
  SET DEFAULT ('TKT-' || lpad(nextval('it_tickets_ticket_number_seq')::text, 6, '0'));

CREATE SEQUENCE IF NOT EXISTS it_purchase_requests_request_number_seq START 42;
ALTER TABLE it_purchase_requests ALTER COLUMN request_number
  SET DEFAULT ('PR-' || lpad(nextval('it_purchase_requests_request_number_seq')::text, 6, '0'));
